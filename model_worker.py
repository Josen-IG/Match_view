"""Entry point executed by each model's own Python environment (3.9+ syntax)."""
from pathlib import Path
import argparse
import json
import math
import os
import sys


def action_inference(video, output):
    from huggingface_hub import snapshot_download
    from opensportslib.apis import LocalizationModel
    from opensportslib.core.config.editable import Config
    if sys.version_info < (3, 12):
        raise RuntimeError("OpenSportsLib integration requires Python >=3.12.")
    folder = Path(snapshot_download(
        "OpenSportsLab/OSL-loc-snbas-2025-e2e", revision="54e24a6", token=False,
        allow_patterns=["config.yaml", "model.pt"],
    ))
    config_path = folder / "config.yaml"
    document = Config.from_file(config_path).get_config()
    # The model was trained with DALI, but the current library has an OpenCV
    # video reader for the same architecture. Avoid installing CUDA-only DALI.
    document["SYSTEM"]["device"] = "cpu"
    document["SYSTEM"]["gpu"]["count"] = 0
    document["DATA"]["common"]["runtime"]["loader_backend"] = "opencv"
    document["TRAIN"]["execution"]["multi_gpu"] = False
    for split in document["DATA"]["common"]["splits"].values():
        kind = split.get("type", "")
        split["type"] = {"VideoGameWithDali": "VideoGameWithOpencv",
                         "VideoGameWithDaliVideo": "VideoGameWithOpencvVideo"}.get(kind, kind)
        split["dataloader"] = dict(batch_size=1, shuffle=False, num_workers=0, pin_memory=False)
    config = Config(document, source=config_path)
    config.update(runtime={"device": "cpu", "output_dir": str(output.parent / "osl-run")},
                  inference={"batch_size": 1, "num_workers": 0})
    model = LocalizationModel(config=config, weights=str(folder / "model.pt"))
    predictions = model.infer(video_path=str(video), use_wandb=False)
    output.write_text(json.dumps(predictions, ensure_ascii=False), encoding="utf-8")


def export_gamestate_state(state_path, video, output):
    """Read only the state just generated by our TrackLab run in this worker."""
    import zipfile
    import pandas as pd
    import cv2
    cap = cv2.VideoCapture(str(video))
    try:
        fps, width, height = [cap.get(key) for key in (
            cv2.CAP_PROP_FPS, cv2.CAP_PROP_FRAME_WIDTH, cv2.CAP_PROP_FRAME_HEIGHT)]
    finally:
        cap.release()
    if not all(math.isfinite(v) and v > 0 for v in (fps, width, height)):
        raise ValueError("Invalid Game State video metadata.")
    rows = []
    with zipfile.ZipFile(state_path) as archive:
        for name in archive.namelist():
            if not name.endswith(".pkl") or name.endswith("_image.pkl"):
                continue
            image_name = name[:-4] + "_image.pkl"
            with archive.open(name) as stream:
                detections = pd.read_pickle(stream)
            with archive.open(image_name) as stream:
                images = pd.read_pickle(stream)
            frame_by_id = images["frame"].to_dict()
            for _, row in detections.iterrows():
                frame = frame_by_id.get(row.get("image_id"))
                bbox = row.get("bbox_ltwh")
                track = row.get("track_id")
                if frame is None or bbox is None or track is None or pd.isna(track):
                    continue
                x, y, w, h = map(float, bbox)
                if not all(math.isfinite(v) for v in (x, y, w, h)) or w <= 0 or h <= 0:
                    continue
                jersey = row.get("jn_tracklet", row.get("jersey_number"))
                jersey = str(jersey).removesuffix(".0") if jersey is not None else ""
                if not jersey.isdigit() or not 0 <= int(jersey) <= 99:
                    jersey = None
                else:
                    jersey = int(jersey)
                team = str(row.get("team"))
                role = str(row.get("role"))
                rows.append({
                    "frame": int(frame), "external_track_id": int(track),
                    "box": [(x+w/2)/width*100, (y+h/2)/height*100, w/width*100, h/height*100],
                    "jersey_number": jersey,
                    "role": role if role in ("player", "goalkeeper", "referee", "other") else None,
                    "team": team if team in ("left", "right") else None,
                })
    output.write_text(json.dumps({"source": "soccernet_gamestate", "fps": fps,
                                  "detections": rows}, ensure_ascii=False), encoding="utf-8")


def gamestate_inference(video, output, root):
    if sys.version_info[:2] != (3, 9):
        raise RuntimeError("sn-gamestate requires its separate Python 3.9 environment.")
    root = root.resolve()
    if not (root / "sn_gamestate").is_dir():
        raise FileNotFoundError("sn-gamestate checkout not found.")
    state_path = output.parent / "gamestate.pklz"
    # The pipeline and checkpoints are from the installed official project.
    # Hydra gets explicit paths; no shell evaluation or YouTube URL involved.
    quote = lambda p: json.dumps(str(p).replace("\\", "/"))
    sys.argv = ["tracklab", "-cn", "soccernet", "dataset=video",
                "dataset.video_path=" + quote(video), "dataset.eval_set=val",
                "project_dir=" + quote(root), "home_dir=" + quote(Path.home()),
                "state.save_file=" + quote(state_path), "eval_tracking=False",
                "visualization.cfg.save_videos=False", "use_wandb=False",
                "hydra.run.dir=" + quote(output.parent / "gsr-run")]
    os.chdir(root)
    from tracklab.main import main
    result = main()
    if result not in (None, 0) or not state_path.is_file():
        raise RuntimeError("Game State did not produce its expected tracker state.")
    export_gamestate_state(state_path, video, output)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("kind", choices=["actions", "gamestate"])
    parser.add_argument("--video", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--root", type=Path)
    args = parser.parse_args()
    video, output = args.video.resolve(), args.output.resolve()
    if not video.is_file():
        raise FileNotFoundError(video)
    output.parent.mkdir(parents=True, exist_ok=True)
    if args.kind == "actions":
        action_inference(video, output)
    else:
        if args.root is None:
            parser.error("--root is required for Game State")
        gamestate_inference(video, output, args.root)


if __name__ == "__main__":
    main()
